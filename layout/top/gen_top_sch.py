"""Schematic of dsm_top generated from topdef.py (the same NETS table the router uses, so layout and schematic cannot drift apart).
Writes dsm_top_sch.spice: the block subcircuits (copied from their *_sch.spice files) and the top subcircuit `dsm_top`
that instantiates every block of FLOORPLAN and connects its pins by net name.  usage: python3 gen_top_sch.py"""
import os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import topdef as T
HERE = os.path.dirname(os.path.abspath(__file__))

def block_def(name):
    txt = open(os.path.join(T.BASE, T.BLOCKS[name][1])).read()
    m = re.search(r'^\.subckt\s+(\S+)\s+(.*)$', txt, re.M)
    ports = m.group(2).split()
    return txt, m.group(1), ports

# (instance, pin) -> net
pin_net = {}
for net, pins in T.NETS.items():
    for inst, pin in pins:
        if inst != 'TOP':
            assert (inst, pin) not in pin_net, (inst, pin); pin_net[(inst, pin)] = net
out = ['* dsm_top: first-order switched-capacitor delta-sigma modulator, generated by gen_top_sch.py from topdef.py', '* top-level ports: ' + ' '.join(T.TOP_PORTS), '']
used = {}
for inst, (cell, x, y) in T.FLOORPLAN.items():
    txt, sub, ports = block_def(cell); used[cell] = txt
for cell, txt in used.items():
    out.append(f'* ---- block {cell} ({T.BLOCKS[cell][1]}) ----'); out.append(txt.strip()); out.append('')
out.append('* ---- top level ----')
out.append('.subckt dsm_top ' + ' '.join(T.TOP_PORTS))
for inst, (cell, x, y) in T.FLOORPLAN.items():
    txt, sub, ports = block_def(cell)
    conn = []
    for p in ports:
        if (inst, p) in pin_net: conn.append(pin_net[(inst, p)])
        else: raise SystemExit(f'pin {inst}.{p} of {cell} is not in topdef.NETS')
    out.append(f'X{inst} ' + ' '.join(conn) + f' {sub}')
out.append('.ends'); out.append('')
open(os.path.join(HERE, 'dsm_top_sch.spice'), 'w').write('\n'.join(out))
print('wrote dsm_top_sch.spice:', len(T.FLOORPLAN), 'instances,', len(set(pin_net.values())), 'nets')
